alter table public.orders add column if not exists customer_id bigint;
alter table public.orders add column if not exists quotation_id bigint;
alter table public.payments add column if not exists customer_id bigint;
alter table public.quotations add column if not exists customer_id bigint;
alter table public.room_captures add column if not exists customer_id bigint;
alter table public.room_captures add column if not exists quotation_id bigint;

update public.orders o set customer_id = c.id from public.customers c where o.customer = c.name;
update public.orders o set quotation_id = q.id from public.quotations q where o.invoice = q.quotation_number;
update public.payments p set customer_id = c.id from public.customers c where p.customer = c.name;
update public.quotations q set customer_id = c.id from public.customers c where q.customer_name = c.name;
update public.room_captures r set customer_id = c.id from public.customers c where r.customer_name = c.name;
update public.room_captures r set quotation_id = q.id from public.quotations q where r.quote_number = q.quotation_number;

create table if not exists public.quotation_items (
  id bigint generated by default as identity primary key,
  quotation_id bigint not null references public.quotations(id) on delete cascade,
  inventory_id bigint references public.inventory(id) on delete set null,
  product_name text not null,
  quantity numeric not null default 1,
  unit text,
  unit_price numeric not null default 0,
  line_total numeric not null default 0,
  created_at timestamptz not null default now()
);

alter table public.quotation_items enable row level security;
drop policy if exists "Authenticated users can read quotation items" on public.quotation_items;
create policy "Authenticated users can read quotation items" on public.quotation_items for select to authenticated using (true);
drop policy if exists "Authenticated users can manage quotation items" on public.quotation_items;
create policy "Authenticated users can manage quotation items" on public.quotation_items for all to authenticated using (true) with check (true);

insert into public.quotation_items (quotation_id, inventory_id, product_name, quantity, unit, unit_price, line_total)
select q.id, i.id, item->>'name', coalesce((item->>'qty')::numeric, 1), item->>'uom', coalesce((item->>'price')::numeric, 0), coalesce((item->>'lineTotal')::numeric, 0)
from public.quotations q
cross join lateral jsonb_array_elements(q.items) item
left join public.inventory i on i.product_code = item->>'name'
where not exists (
  select 1 from public.quotation_items qi
  where qi.quotation_id = q.id and qi.product_name = item->>'name'
);

create table if not exists public.payment_requests (
  id uuid primary key default gen_random_uuid(),
  quote_number text unique,
  customer_id bigint references public.customers(id) on delete set null,
  customer_name text not null,
  customer_phone text not null default '',
  customer_email text not null,
  item_name text not null,
  panels integer not null default 0,
  unit_price numeric not null default 0,
  subtotal numeric not null default 0,
  vat numeric not null default 0,
  total_amount numeric not null default 0,
  summary text not null default '',
  street_address text not null default '',
  city_province text not null default '',
  postal_code text not null default '',
  payment_method text not null default '',
  delivery_method text not null default '',
  room_capture_url text,
  source text not null default 'Customer App',
  status text not null default 'Pending Review',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.payment_requests
  add column if not exists customer_phone text not null default '',
  add column if not exists summary text not null default '',
  add column if not exists street_address text not null default '',
  add column if not exists city_province text not null default '',
  add column if not exists postal_code text not null default '',
  add column if not exists payment_method text not null default '',
  add column if not exists delivery_method text not null default '',
  add column if not exists room_capture_url text,
  add column if not exists source text not null default 'Customer App',
  add column if not exists updated_at timestamptz not null default now();

alter table public.payment_requests enable row level security;
drop policy if exists "Authenticated users can read payment requests" on public.payment_requests;
create policy "Authenticated users can read payment requests" on public.payment_requests for select to authenticated using (true);
drop policy if exists "Authenticated users can manage payment requests" on public.payment_requests;
create policy "Authenticated users can manage payment requests" on public.payment_requests for all to authenticated using (true) with check (true);

insert into public.payment_requests (quote_number, customer_id, customer_name, customer_phone, customer_email, item_name, panels, unit_price, subtotal, vat, total_amount, status, notes, created_at)
select case when q.id is not null then x->>'quote_number' else null end, c.id, x->>'customer_name', coalesce(x->>'customer_phone',''), x->>'customer_email', x->>'item_name', coalesce((x->>'panels')::integer,0), coalesce((x->>'unit_price')::numeric,0), coalesce((x->>'subtotal')::numeric,0), coalesce((x->>'vat')::numeric,0), coalesce((x->>'total_amount')::numeric,0), coalesce(x->>'status','Pending Review'), coalesce(x->>'notes',''), nullif(x->>'created_at','')::timestamptz
from jsonb_array_elements((select data from public.project_data where data_type = 'payment_requests' and external_id = 'all')) x
left join public.customers c on c.name = x->>'customer_name'
left join public.quotations q on q.quotation_number = x->>'quote_number'
on conflict (quote_number) do nothing;

