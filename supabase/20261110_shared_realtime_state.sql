-- Store one shared operational snapshot so every app instance reads the same
-- state. The secret-key backend writes/reads this row; customer clients must
-- never read the complete company snapshot directly.

create table if not exists public.project_data (
  id bigint generated by default as identity primary key,
  data_type text not null,
  external_id text not null,
  data jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (data_type, external_id)
);

alter table public.project_data
  add column if not exists updated_at timestamptz not null default now();

alter table public.project_data enable row level security;

drop policy if exists "Authenticated users can read project data" on public.project_data;
create policy "Authenticated users can read project data"
on public.project_data for select to authenticated
using (data_type <> 'app_state');

drop policy if exists "Authenticated users can write project data" on public.project_data;
create policy "Authenticated users can write project data"
on public.project_data for all to authenticated
using (data_type <> 'app_state')
with check (data_type <> 'app_state');

create or replace function public.set_project_data_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_project_data_updated_at on public.project_data;
create trigger set_project_data_updated_at
before update on public.project_data
for each row execute function public.set_project_data_updated_at();

do $$
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    execute 'create publication supabase_realtime';
  end if;

  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'project_data'
  ) then
    execute 'alter publication supabase_realtime add table public.project_data';
  end if;
end;
$$;

insert into public.project_data (data_type, external_id, data)
values (
  'app_state_config',
  'shared',
  '{"schema_version":1,"private_state_row":true}'::jsonb
)
on conflict (data_type, external_id)
do update set data = excluded.data;
